"""Regenerate the launcher icon layers (app + wear) from code.

    python3 -m venv /tmp/iconvenv && /tmp/iconvenv/bin/pip install fonttools
    /tmp/iconvenv/bin/python tools/icons/make_icon.py

Needs Noto Serif Black (Fedora: google-noto-serif-fonts).
"""
import sys, re, math, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from glyph import glyph_path
HDR='<?xml version="1.0" encoding="utf-8"?>\n'
def vd(body, comment):
    return (HDR+f'<!-- {comment} Generated by tools/icons/make_icon.py. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'+body+'</vector>\n')
def path(d, fill=None, stroke=None, sw=None, cap=None, ind='    '):
    a=[f'android:pathData="{d}"']
    if fill: a.append(f'android:fillColor="{fill}"')
    if stroke: a+= [f'android:strokeColor="{stroke}"', f'android:strokeWidth="{sw}"']
    if cap: a.append(f'android:strokeLineCap="{cap}"')
    return ind+'<path '+(f'\n{ind}    ').join(a)+' />\n'
f=lambda v: f"{v:.2f}".rstrip('0').rstrip('.')
def circle(cx,cy,r): return f"M{f(cx-r)},{f(cy)}a{f(r)},{f(r)} 0 1,0 {f(2*r)},0a{f(r)},{f(r)} 0 1,0 {f(-2*r)},0z"
def rrect(x,y,w,h,r): return (f"M{f(x+r)},{f(y)}h{f(w-2*r)}a{f(r)},{f(r)} 0 0,1 {f(r)},{f(r)}v{f(h-2*r)}a{f(r)},{f(r)} 0 0,1 {f(-r)},{f(r)}"
                               f"h{f(-(w-2*r))}a{f(r)},{f(r)} 0 0,1 {f(-r)},{f(-r)}v{f(-(h-2*r))}a{f(r)},{f(r)} 0 0,1 {f(r)},{f(-r)}z")
def diamond(cx,cy,h): return f"M{f(cx)},{f(cy-h)}L{f(cx+h)},{f(cy)}L{f(cx)},{f(cy+h)}L{f(cx-h)},{f(cy)}z"


BLK='/usr/share/fonts/google-noto/NotoSerif-Black.ttf'
BLUE='#FF1D4E9E'; PAPER='#FFFBF9F4'
t0,t1,rr,gh=22,86,15,34; w=t1-t0
g,_=glyph_path(BLK,'ç',gh,54,55.5)
body=path(rrect(t0,t0,w,w,4),PAPER)
body+=f'    <group>\n        <clip-path android:pathData="{rrect(t0,t0,w,w,4)}" />\n'
for (x,y) in [(t0,t0),(t1,t0),(t0,t1),(t1,t1)]:
    body+=path(circle(x,y,rr),BLUE,ind='        ')+path(circle(x,y,rr*0.62),PAPER,ind='        ')+path(circle(x,y,rr*0.3),BLUE,ind='        ')
for (x,y) in [(54,t0),(54,t1),(t0,54),(t1,54)]:
    body+=path(diamond(x,y,5.66),BLUE,ind='        ')
body+='    </group>\n'+path(g,BLUE)
pt_fg=vd(body,'Azulejo tile with a serif c-cedilla.')
gm,_=glyph_path(BLK,'ç',40,54,55.5)
mono=path(gm,'#FF000000')
pt_mono=vd(mono,'Themed-icon layer: the c-cedilla alone.')



root=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','..')
for mod in ('app','wear'):
    res=os.path.join(root,mod,'src','main','res','drawable')
    open(os.path.join(res,'ic_launcher_foreground.xml'),'w').write(pt_fg)
    open(os.path.join(res,'ic_launcher_monochrome.xml'),'w').write(pt_mono)
print('wrote app + wear icon layers')
